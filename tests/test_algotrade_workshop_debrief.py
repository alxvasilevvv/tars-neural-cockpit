def _bar(*, ts: float, price: float, instrument: str) -> dict:
    return {
        "ts": ts,
        "open": price,
        "high": price,
        "low": price,
        "close": price,
        "volume": 1.0,
        "instrument": instrument,
    }


def _drive_round_trip(
    sandbox_id: str,
    *,
    open_price: float,
    close_price: float,
    instrument: str = "BINANCE:BTCUSDT",
) -> str:
    name = list_recipes()[0]
    fp = get_registry().put(load_recipe(name)).fingerprint
    runtime = get_runtime()
    wiring = runtime.start_paper_session(
        strategy_fingerprint=fp,
        instrument=instrument,
        sandbox_id=sandbox_id,
    )

    async def run() -> None:
        await wiring.router.submit(
            OrderIntent.make(
                strategy_fingerprint=fp,
                instrument=instrument,
                side=Side.BUY,
                qty=1.0,
                type=OrderType.MARKET,
            )
        )
        await wiring.adapter.on_bar(
            _bar(ts=1.0, price=open_price, instrument=instrument),
            instrument=instrument,
        )
        await wiring.router.submit(
            OrderIntent.make(
                strategy_fingerprint=fp,
                instrument=instrument,
                side=Side.SELL,
                qty=1.0,
                type=OrderType.MARKET,
            )
        )
        await wiring.adapter.on_bar(
            _bar(ts=2.0, price=close_price, instrument=instrument),
            instrument=instrument,
        )

    asyncio.run(run())
    return wiring.session.session_id


