def test_debrief_empty_workshop_renders_skeleton(tars_home: Path) -> None:
    store = get_lab_store()
    store.create_workshop(name="Empty", workshop_id="ws_empty")
    debrief = render_workshop_debrief("ws_empty")
    md = debrief.markdown
    assert md.startswith("# Workshop debrief — Empty")
    assert "## Workshop" in md
    assert "## Leaderboard" in md
    assert "_no attendees enrolled yet._" in md
    assert "_Generated by TARS algotrade_" not in md
    assert "Generated by TARS algotrade" in md  # in footer


def test_debrief_renders_full_bundle_with_sessions(tars_home: Path) -> None:
    store = get_lab_store()
    store.create_workshop(name="Cresco", workshop_id="ws_c")
    a = store.enroll(
        workshop_id="ws_c",
        display_name="Alice",
        attendee_id="att_alice",
    )
    b = store.enroll(
        workshop_id="ws_c",
        display_name="Bob",
        attendee_id="att_bob",
    )
    _drive_round_trip(a.sandbox_id, open_price=100.0, close_price=120.0)
    _drive_round_trip(b.sandbox_id, open_price=100.0, close_price=80.0)

    debrief = render_workshop_debrief("ws_c")

    # Workshop header.
    assert "ws_c" in debrief.markdown
    assert "## Workshop" in debrief.markdown
    # Leaderboard table.
    assert "| Rank | Attendee | Sessions" in debrief.markdown
    assert "| 1 | Alice |" in debrief.markdown
    assert "| 2 | Bob |" in debrief.markdown
    # Per-attendee sections in rank order.
    alice_idx = debrief.markdown.find("### Alice")
    bob_idx = debrief.markdown.find("### Bob")
    assert 0 < alice_idx < bob_idx
    # Each attendee section embeds at least one session report
    # (top heading pushed three levels deeper: # → ####).
    assert "#### Session" in debrief.markdown


def test_debrief_skip_session_reports(tars_home: Path) -> None:
    store = get_lab_store()
    store.create_workshop(name="HeadlineOnly", workshop_id="ws_h")
    a = store.enroll(
        workshop_id="ws_h", display_name="Alice", attendee_id="att_a"
    )
    _drive_round_trip(a.sandbox_id, open_price=100.0, close_price=110.0)

    debrief = render_workshop_debrief(
        "ws_h", include_session_reports=False
    )
    # Headlines still there.
    assert "### Alice" in debrief.markdown
    # No embedded session report.
    assert "##### Session" not in debrief.markdown
    assert "Headline metrics" not in debrief.markdown


def test_debrief_consensus_returns_valid_severity(tars_home: Path) -> None:
    """The aggregated consensus must be one of the three valid
    severity levels — even for a session that doesn't trip any
    voice (which produces ``info`` as the default consensus)."""

    store = get_lab_store()
    store.create_workshop(name="Sev", workshop_id="ws_s")
    bob = store.enroll(
        workshop_id="ws_s", display_name="Bob", attendee_id="att_bob"
    )
    _drive_round_trip(bob.sandbox_id, open_price=100.0, close_price=50.0)

    debrief = render_workshop_debrief("ws_s")
    bob_block = next(a for a in debrief.attendees if a.attendee.attendee_id == "att_bob")
    assert bob_block.council_consensus in {"info", "warn", "alert"}
    # The bundled markdown surfaces the consensus too.
    assert (
        f"**Council consensus**: {bob_block.council_consensus}"
        in debrief.markdown
    )


def test_debrief_to_dict_round_trips(tars_home: Path) -> None:
    store = get_lab_store()
    store.create_workshop(name="RT", workshop_id="ws_rt")
    store.enroll(
        workshop_id="ws_rt",
        display_name="Solo",
        attendee_id="att_solo",
    )
    debrief = render_workshop_debrief("ws_rt")
    d = debrief.to_dict()
    assert d["workshop"]["workshop_id"] == "ws_rt"
    assert d["leaderboard"]["workshop_id"] == "ws_rt"
    assert isinstance(d["attendees"], list)
    assert len(d["attendees"]) == 1
    assert d["attendees"][0]["attendee"]["attendee_id"] == "att_solo"
    assert "markdown" in d
    assert isinstance(d["markdown"], str)
    assert d["rendered_at"] > 0


