"""Tests for the live Tauri updater channel HTTP surface.

The channel JSON is consumed by ``tauri-plugin-updater`` and must
stay in lock-step with ``/api/product/downloads`` (both pull from
the same in-memory :class:`DownloadManifest`). This suite covers:

1. The bridge primitives (``known_targets``, ``target_to_os_arch``,
   ``build_channel_from_release``).
2. The HTTP endpoints
   (``GET /updates/{target}/{version}.json``,
   ``GET /api/product/updater/targets``):
   - 200 with the expected wire shape for every supported target
   - 404 for unknown targets
   - 404 when no release exists for the target's OS
   - cache + custom headers
   - lock-step with ``/api/product/downloads``
"""

from __future__ import annotations

from pathlib import Path

import pytest


