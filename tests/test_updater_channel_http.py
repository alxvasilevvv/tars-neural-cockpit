def test_build_channel_picks_up_sidecar_signatures(tmp_path: Path):
    from backend.core.product.updater import build_channel_from_release
    from backend.core.product.manifest import ReleaseEntry, ReleaseArtifact

    artifact_path = tmp_path / "TARS-1.2.3-arm64.dmg"
    artifact_path.write_bytes(b"binary")
    sig_path = tmp_path / "TARS-1.2.3-arm64.dmg.sig"
    sig_path.write_text("untrusted-comment\n<base64sig>\n", encoding="utf-8")

    entry = ReleaseEntry(
        version="1.2.3",
        channel="stable",
        released_at="2026-06-01T00:00:00Z",
        notes=None,
        artifacts=(
            ReleaseArtifact(
                os="macos",
                arch="arm64",
                kind="dmg",
                filename="TARS-1.2.3-arm64.dmg",
                url="https://example.com/1.2.3/arm64.dmg",
            ),
        ),
    )
    channel = build_channel_from_release(
        entry, target="darwin-aarch64", artifacts_dir=tmp_path
    )
    assert len(channel.platforms) == 1
    sig = channel.platforms[0].signature
    assert "<base64sig>" in sig


