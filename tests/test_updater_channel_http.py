def test_http_updater_channel_returns_tauri_shape(client):
    resp = client.get("/updates/darwin-aarch64/0.0.0.json")
    assert resp.status_code == 200
    body = resp.json()
    assert "version" in body
    assert "pub_date" in body
    assert "platforms" in body
    assert "darwin-aarch64" in body["platforms"]
    plat = body["platforms"]["darwin-aarch64"]
    # Tauri requires both fields on every platform entry.
    assert "url" in plat
    assert "signature" in plat
    # Custom header lets monitors filter logs by target.
    assert resp.headers.get("x-tars-updater-target") == "darwin-aarch64"


def test_http_updater_channel_serves_each_known_target(client):
    """Every target advertised by ``known_targets`` must either
    serve a 200 (default manifest covers it) or a 404 with a
    ``no_release_for_target`` detail (default manifest skips it).

    No target should crash, hit an unknown_target 404, or return
    a body without the Tauri-required keys."""

    targets_resp = client.get("/api/product/updater/targets")
    targets = targets_resp.json()["targets"]

    for target in targets:
        resp = client.get(f"/updates/{target}/0.0.0.json")
        assert resp.status_code in (200, 404), f"target={target}"
        if resp.status_code == 200:
            body = resp.json()
            assert "version" in body
            assert "platforms" in body
            assert target in body["platforms"]
        else:
            assert resp.json()["detail"] == "no_release_for_target"


def test_http_updater_channel_unknown_target_returns_404(client):
    resp = client.get("/updates/haiku-aarch64/0.0.0.json")
    assert resp.status_code == 404
    assert resp.json()["detail"] == "unknown_target"


def test_http_updater_channel_path_with_pre_release_version(client):
    """The ``current_version`` segment is informational — Tauri
    embeds the installed build's semver. We accept anything that
    doesn't break path routing (no slashes / .json suffix)."""

    resp = client.get(
        "/updates/darwin-aarch64/0.1.0-alpha.5%2Bbuild.123.json"
    )
    assert resp.status_code in (200, 404)


def test_http_updater_channel_lock_step_with_downloads(client):
    """The Tauri channel must report the same version as
    ``/api/product/downloads/latest`` for the same OS — that's
    the lock-step contract."""

    downloads = client.get(
        "/api/product/downloads/latest?os=macos"
    ).json()
    expected_version = downloads["release"]["version"]

    channel = client.get("/updates/darwin-aarch64/0.0.0.json").json()
    assert channel["version"] == expected_version


def test_http_updater_channel_caches_for_one_minute(client):
    resp = client.get("/updates/darwin-aarch64/0.0.0.json")
    assert resp.status_code in (200, 404)
    if resp.status_code == 200:
        cache = resp.headers.get("cache-control", "")
        assert "max-age=60" in cache


def test_http_updater_channel_pulls_from_load_manifest(monkeypatch, client):
    """When ``load_manifest`` returns an entry with no artifact for
    the requested OS, the endpoint should 404 instead of returning
    an empty platforms map (which would confuse Tauri)."""

    from backend.core.product.manifest import (
        DownloadManifest,
        ReleaseArtifact,
        ReleaseEntry,
        CONTRACT_VERSION,
    )
    from web_extras.routers import product as product_router

    fake_entry = ReleaseEntry(
        version="2.0.0",
        channel="stable",
        released_at="2026-05-01T00:00:00Z",
        notes=None,
        artifacts=(
            ReleaseArtifact(
                os="windows",
                arch="x64",
                kind="msi",
                filename="TARS-2.0.0.msi",
                url="https://example.com/2.0.0/setup.msi",
            ),
        ),
    )
    fake_manifest = DownloadManifest(
        product="tars",
        contract_version=CONTRACT_VERSION,
        channel="stable",
        released_at="2026-05-01T00:00:00Z",
        releases=(fake_entry,),
        source="defaults",
    )
    monkeypatch.setattr(
        product_router, "load_manifest", lambda: fake_manifest
    )

    # macOS has no artifact in the fake manifest → 404.
    resp = client.get("/updates/darwin-aarch64/0.0.0.json")
    assert resp.status_code == 404

    # Windows is present → 200.
    resp = client.get("/updates/windows-x86_64/0.0.0.json")
    assert resp.status_code == 200
    body = resp.json()
    assert body["version"] == "2.0.0"
    assert body["platforms"]["windows-x86_64"]["url"].endswith("setup.msi")


def test_http_updater_channel_signature_passthrough(monkeypatch, client, tmp_path: Path):
    """If a sidecar ``.sig`` exists alongside the artifact bytes,
    the channel surfaces its content verbatim. We can't easily
    drop a sidecar onto the live ``meeet.world`` URL, so the
    bridge runs in two modes — without ``artifacts_dir`` (HTTP
    serves "no signature") and with one (CLI mode). This test
    pins the HTTP behaviour: signature is always an empty string
    when the manifest doesn't include one explicitly."""

    resp = client.get("/updates/darwin-aarch64/0.0.0.json")
    if resp.status_code == 200:
        body = resp.json()
        sig = body["platforms"]["darwin-aarch64"]["signature"]
        # The default-bundle manifest doesn't ship signatures, so
        # the live endpoint surfaces empty strings.
        assert sig == ""
